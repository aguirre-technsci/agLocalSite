"""Teste de navegador da escrita: cria nota, edita, marca checklist, atualiza sozinho, conflito, servidor parado.

Precisa de: pip install playwright && playwright install chromium (só para este teste).
Uso: python3 tests/escrita_navegador.py

Roda numa CÓPIA da pasta do projeto, com um serve.py próprio em porta livre: os arquivos reais não são tocados.
Sem argumento, as capturas de tela ficam em /tmp/ag-telas (mude com AG_TELAS=pasta).
"""

import os as _os, sys as _sys
if not _os.path.isdir(_os.path.join(_os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))), "01-Visao-e-Negocio")):
    print("PULADO: este teste usa os documentos do projeto de origem (pasta 01-Visao-e-Negocio/), que não vêm neste zip.")
    _sys.exit(77)

import json
import os
import shutil
import sys

from playwright.sync_api import expect, sync_playwright

from _navegador import (RAIZ, TELAS, abrir, confere, contraste, copiar, escrever, escrita_ligada, falhas, fim, ler,
                        porta_livre, subir)

def main():
    os.makedirs(TELAS, exist_ok=True)
    tmp, dest = copiar()
    porta = porta_livre()
    base = f"http://localhost:{porta}/"
    srv = subir(dest, porta)
    try:
        with sync_playwright() as p:
            b = p.chromium.launch()
            ctx = b.new_context(viewport={"width": 1280, "height": 900})
            page = ctx.new_page()
            dialogos = []
            page.on("dialog", lambda d: (dialogos.append(d.message), d.accept()))

            print("1. Sem servidor com escrita o site é só de leitura")
            leitura = b.new_page()
            leitura.goto("file://" + os.path.join(RAIZ, "site", "index.html"))
            leitura.wait_for_selector(".item-btn")
            leitura.wait_for_timeout(600)
            confere(not leitura.locator("#ag-plus").is_visible() and not leitura.locator("#ag-bar").is_visible(),
                    "file://: sem botão + e sem barra Editar")
            leitura.keyboard.press("Control+k")
            confere(leitura.locator(".ag-fundo").count() == 0, "file://: Ctrl+K não abre nada")
            leitura.close()

            print("2. Criar nota pela barra Ctrl+K, sem F5")
            abrir(page, base, "#01-visao-e-negocio-publico-alvo")
            escrita_ligada(page)
            page.screenshot(path=f"{TELAS}/01-lado-a-lado.png")
            page.locator("#content h1").click()  # foco fora de campos
            page.keyboard.press("Control+k")
            expect(page.locator(".ag-paleta")).to_be_visible()
            confere(page.get_attribute(".ag-dialogo", "aria-modal") == "true" and page.get_attribute(".ag-dialogo", "role") == "dialog",
                    "palette: role=dialog e aria-modal")
            confere(page.get_attribute(".ag-paleta input", "role") == "combobox", "palette: campo é combobox")
            confere(page.evaluate("document.activeElement.tagName") == "INPUT", "palette: foco no campo ao abrir")
            confere(page.locator(".ag-op").first.inner_text().startswith("Nova nota"), "palette: 'Nova nota' vem primeiro")
            page.screenshot(path=f"{TELAS}/02-paleta.png")
            alturas = page.eval_on_selector_all(".ag-op", "e => e.map(x => x.getBoundingClientRect().height)")
            confere(min(alturas) >= 44, f"palette: itens com pelo menos 44 px (mín. {min(alturas):.0f})")
            page.keyboard.type("nova")
            page.keyboard.press("Escape")
            expect(page.locator(".ag-fundo")).to_have_count(0)
            confere(True, "palette: fecha com Esc")
            page.click("#ag-plus")
            page.keyboard.type("publico")
            expect(page.locator(".ag-op")).to_have_count(1)
            page.keyboard.press("Escape")
            confere(page.evaluate("document.activeElement.id") == "ag-plus", "palette: foco volta ao botão que abriu")
            page.click("#ag-plus")
            page.keyboard.type("nova")
            page.keyboard.press("Enter")
            expect(page.locator(".ag-nova")).to_be_visible()
            confere(page.input_value(".ag-nova select") == "01-Visao-e-Negocio", "nova nota: pasta padrão é a do documento aberto")
            page.fill(".ag-nova label:has-text('Título') input", "")
            page.locator(".ag-nova textarea").fill("# Reunião de Sexta\n\n- [ ] levar dados\n")
            confere(page.input_value(".ag-nova label:has-text('Título') input") == "Reunião de Sexta", "nova nota: título vem do '# ' do texto colado")
            confere("01-Visao-e-Negocio/reuniao-de-sexta.md" in page.inner_text(".ag-previa"), "nova nota: prévia mostra o nome do arquivo")
            tagbox = page.locator(".ag-tags input")
            tagbox.fill("mest")
            expect(page.locator(".ag-tags .gv-suggest button").first).to_be_visible()
            confere("mestrado" in page.inner_text(".ag-tags .gv-suggest"), "nova nota: sugere tags existentes, com contagem")
            page.keyboard.press("ArrowDown")
            page.keyboard.press("Enter")
            tagbox.fill("Ideia Nova")
            page.keyboard.press("Enter")
            confere(page.locator(".ag-chip").count() == 2, "nova nota: duas tags viram chips")
            confere("tags: [mestrado, ideia_nova]" in page.inner_text(".ag-previa"), "nova nota: prévia mostra o frontmatter")
            page.screenshot(path=f"{TELAS}/03-nova-nota.png")
            # foco preso dentro do painel
            for _ in range(14):
                page.keyboard.press("Tab")
            confere(page.evaluate("!!document.activeElement.closest('.ag-dialogo')"), "nova nota: Tab não sai do painel")
            page.locator(".ag-nova textarea").focus()
            page.keyboard.press("Control+Enter")
            expect(page.locator(".ag-fundo")).to_have_count(0, timeout=5000)
            nota = "01-Visao-e-Negocio/reuniao-de-sexta.md"
            confere(os.path.exists(os.path.join(dest, nota)), "nota criada no disco")
            confere(ler(dest, nota) == "---\ntags: [mestrado, ideia_nova]\n---\n# Reunião de Sexta\n\n- [ ] levar dados\n", "conteúdo da nota: frontmatter + título mantido do corpo")
            expect(page.locator("#content h1")).to_have_text("Reunião de Sexta", timeout=5000)
            confere(page.locator(f".item-btn[data-id='01-visao-e-negocio-reuniao-de-sexta']").count() == 1, "nota aparece no menu sem F5")
            confere(page.evaluate("location.hash") == "#01-visao-e-negocio-reuniao-de-sexta", "a nota nova abre (id igual ao do sync)")

            print("3. Nome repetido")
            page.click("#ag-plus"); page.keyboard.type("nova"); page.keyboard.press("Enter")
            page.fill(".ag-nova label:has-text('Título') input", "Reunião de Sexta")
            page.keyboard.press("Control+Enter")
            expect(page.locator("#ag-erro-titulo")).to_contain_text("Já existe", timeout=5000)
            confere(page.get_attribute("#ag-erro-titulo", "role") == "alert", "erro 'existe' aparece no campo título (role=alert)")
            page.keyboard.press("Escape")

            print("4. Editar com prévia, Ctrl+S")
            abrir(page, base, "#01-visao-e-negocio-publico-alvo")
            escrita_ligada(page)
            page.click("#ag-bar >> text=Editar")
            expect(page.locator(".ag-texto")).to_be_visible()
            confere(page.input_value(".ag-texto").startswith("---\ntags: [clientes"), "editar: textarea traz o arquivo cru, com frontmatter")
            colunas = page.evaluate("getComputedStyle(document.querySelector('.ag-edicao')).gridTemplateColumns.split(' ').length")
            confere(colunas == 2, "editar: prévia ao lado em 1280 px")
            page.screenshot(path=f"{TELAS}/04-editar.png")
            page.fill(".ag-texto", ler(dest, "01-Visao-e-Negocio/publico-alvo.md") + "\nLinha nova do teste.\n")
            expect(page.locator(".ag-prev")).to_contain_text("Linha nova do teste", timeout=2000)
            confere("Alterações não salvas" in page.inner_text("#ag-bar"), "editar: mostra 'Alterações não salvas'")
            # sair com alteração pendente pergunta antes
            dialogos.clear()
            page.click(".item-btn[data-id='inicio']")
            expect(page.locator("#content h1")).to_contain_text("Bem-vindo")
            confere(any("Descartar" in d for d in dialogos), "editar: trocar de documento com alteração pergunta antes de descartar")
            abrir(page, base, "#01-visao-e-negocio-publico-alvo")
            page.click("#ag-bar >> text=Editar")
            page.fill(".ag-texto", ler(dest, "01-Visao-e-Negocio/publico-alvo.md") + "\nLinha nova do teste.\n")
            page.keyboard.press("Control+s")
            expect(page.locator(".ag-texto")).to_have_count(0, timeout=5000)
            confere(ler(dest, "01-Visao-e-Negocio/publico-alvo.md").endswith("\nLinha nova do teste.\n"), "editar: Ctrl+S gravou no disco")
            expect(page.locator("#content")).to_contain_text("Linha nova do teste")
            hist = os.path.join(dest, ".historico", "01-Visao-e-Negocio", "publico-alvo")
            confere(os.path.isdir(hist) and len(os.listdir(hist)) == 1, "editar: cópia da versão anterior em .historico/")
            page.click("#ag-bar >> text=Editar")
            page.keyboard.press("Escape")
            expect(page.locator(".ag-texto")).to_have_count(0)
            confere(not dialogos[-1:] or "Descartar" not in dialogos[-1] or len(dialogos) == 1, "editar: Esc cancela sem alterações, sem perguntar")

            print("5. Checklist grava no arquivo")
            abrir(page, base, "#inicio")
            escrita_ligada(page)
            caixas = page.locator("#content input[type=checkbox]")
            confere(caixas.count() == 10 and not caixas.first.is_disabled(), "checklist: 10 caixas ativas")
            confere(bool(page.get_attribute("#content input[type=checkbox] >> nth=0", "aria-label")), "checklist: caixa tem nome acessível")
            antes = ler(dest, "INICIO.md")
            caixas.nth(1).click()
            expect(caixas.nth(1)).to_be_checked()
            page.wait_for_timeout(800)
            depois = ler(dest, "INICIO.md")
            dif = [(a, c) for a, c in zip(antes.split("\n"), depois.split("\n")) if a != c]
            confere(len(dif) == 1 and dif[0][1] == dif[0][0].replace("- [ ]", "- [x]") and "Orientador" in dif[0][0], "checklist: só a linha clicada mudou no .md")
            caixas.nth(1).click()
            page.wait_for_timeout(800)
            confere(ler(dest, "INICIO.md") == antes, "checklist: desmarcar volta ao original")
            page.click("#content input[type=checkbox] >> nth=3")
            page.click("#content input[type=checkbox] >> nth=4")
            page.wait_for_timeout(1200)
            marcadas = [l for l in ler(dest, "INICIO.md").split("\n") if l.startswith("- [x]")]
            confere(len(marcadas) == 2, "checklist: dois cliques seguidos gravam os dois")

            print("6. Arquivo alterado por fora aparece sozinho")
            abrir(page, base, "#01-visao-e-negocio-publico-alvo")
            escrita_ligada(page)
            escrever(dest, "01-Visao-e-Negocio/publico-alvo.md", "---\ntags: [clientes]\n---\n# Público-Alvo\n\nEditado no bloco de notas.\n")
            expect(page.locator("#content")).to_contain_text("Editado no bloco de notas", timeout=6000)
            confere(True, "por fora: documento aberto se redesenha em poucos segundos")
            escrever(dest, "06-Financeiro/orcamento-por-fora.md", "---\ntags: [zzz_tag_nova]\n---\n# Orçamento por fora\n")
            page.wait_for_selector(".item-btn:has-text('Orçamento por fora')", state="attached", timeout=6000)
            confere(True, "por fora: arquivo novo entra no menu sem F5")
            ok_tag = page.evaluate("AG_GRAPH.docs.some(d => d.tags.curated.includes('zzz_tag_nova'))")
            confere(ok_tag, "por fora: tags e grafo atualizados")
            page.click("#graph-btn")
            page.fill(".gv-search input", "tag:zzz_tag_nova")
            expect(page.locator(".gv-count")).to_have_text("1 de %d documentos" % page.evaluate("AG_GRAPH.docs.length"))
            page.click("#graph-btn")

            print("7. Conflito")
            abrir(page, base, "#01-visao-e-negocio-publico-alvo")
            escrita_ligada(page)
            page.click("#ag-bar >> text=Editar")
            page.fill(".ag-texto", "---\ntags: [clientes]\n---\n# Meu texto\n")
            escrever(dest, "01-Visao-e-Negocio/publico-alvo.md", "# Texto de fora\n")
            expect(page.locator(".ag-faixa")).to_contain_text("mudou por fora", timeout=6000)
            confere(page.input_value(".ag-texto").startswith("---\ntags: [clientes]\n---\n# Meu texto"), "conflito: o texto digitado não é tocado")
            page.screenshot(path=f"{TELAS}/05-conflito.png")
            page.click(".ag-faixa >> text=Sobrescrever com a minha")
            expect(page.locator(".ag-texto")).to_have_count(0, timeout=5000)
            confere("# Meu texto" in ler(dest, "01-Visao-e-Negocio/publico-alvo.md"), "conflito: 'sobrescrever com a minha' grava o texto digitado")
            page.click("#ag-bar >> text=Editar")
            page.fill(".ag-texto", "# Outra minha\n")
            escrever(dest, "01-Visao-e-Negocio/publico-alvo.md", "# De fora de novo\n")
            expect(page.locator(".ag-faixa")).to_contain_text("mudou por fora", timeout=6000)
            dialogos.clear()
            page.click(".ag-faixa >> text=Ver a nova versão")
            expect(page.locator(".ag-texto")).to_have_count(0, timeout=5000)
            confere(any("Descartar" in d for d in dialogos), "conflito: 'ver a nova versão' pergunta antes de descartar o digitado")
            expect(page.locator("#content")).to_contain_text("De fora de novo")
            # 409 do servidor (a página ainda não sabe da mudança): bloqueia a consulta e salva
            versao = page.evaluate("fetch('/api/versao').then(r => r.json())")
            page.route("**/api/versao", lambda r: r.fulfill(status=200, content_type="application/json", body=json.dumps(versao)))
            page.click("#ag-bar >> text=Editar")
            page.fill(".ag-texto", "# Minha tentativa\n")
            escrever(dest, "01-Visao-e-Negocio/publico-alvo.md", "# Mudou sem a página saber\n")
            os.utime(os.path.join(dest, "01-Visao-e-Negocio/publico-alvo.md"), ns=(2_000_000_000_000_000_000,) * 2)
            page.click("#ag-bar >> text=Salvar")
            expect(page.locator(".ag-faixa")).to_contain_text("mudou por fora", timeout=5000)
            confere(ler(dest, "01-Visao-e-Negocio/publico-alvo.md") == "# Mudou sem a página saber\n", "conflito 409: nada foi gravado")
            page.unroute("**/api/versao")
            page.click(".ag-faixa >> text=Sobrescrever com a minha")
            expect(page.locator(".ag-texto")).to_have_count(0, timeout=5000)
            confere(ler(dest, "01-Visao-e-Negocio/publico-alvo.md") == "# Minha tentativa\n", "conflito 409: sobrescrever reenvia com o mtime devolvido")

            print("8. Servidor parado volta ao modo leitura; ao voltar, a escrita volta")
            abrir(page, base, "#inicio")
            escrita_ligada(page)
            srv.terminate(); srv.wait()
            expect(page.locator("#ag-plus")).to_be_hidden(timeout=6000)
            confere(page.locator("#content input[type=checkbox]").first.is_disabled(), "servidor parado: caixas voltam a desativadas")
            confere("modo leitura" in page.inner_text(".ag-faixa"), "servidor parado: avisa uma vez")
            confere(page.locator("#ag-bar >> text=Editar").count() == 0, "servidor parado: botão Editar some")
            srv = subir(dest, porta)
            expect(page.locator("#ag-plus")).to_be_visible(timeout=8000)
            confere(page.locator(".ag-faixa").count() == 0, "servidor de volta: o aviso some e a escrita volta")

            print("9. Layout e acessibilidade")
            page.set_viewport_size({"width": 1000, "height": 800})
            page.click("#ag-bar >> text=Editar")
            colunas = page.evaluate("getComputedStyle(document.querySelector('.ag-edicao')).gridTemplateColumns.split(' ').length")
            confere(colunas == 1, "editar: prévia empilhada abaixo de 1100 px")
            page.keyboard.press("Escape")
            for tema in ("claro", "escuro"):
                if tema == "escuro":
                    page.click("#theme-btn")
                abrir(page, base, "#00-documento-base-documento-base")
                c = contraste(page, "#content a.doc-link code", "#content a.doc-link code")
                confere(c >= 4.5, f"link de citação, tema {tema}: contraste {c:.2f}:1 (mínimo 4,5)")
                page.click("#ag-plus")
                page.screenshot(path=f"{TELAS}/06-paleta-{tema}.png")
                page.keyboard.press("Escape")
                page.click("#ag-bar >> text=Editar")
                page.screenshot(path=f"{TELAS}/07-editar-{tema}.png")
                page.keyboard.press("Escape")
            altura = page.evaluate("[...document.querySelectorAll('#ag-bar .ag-btn, #ag-plus')].map(e => e.getBoundingClientRect().height)")
            confere(altura and min(altura) >= 44, "botões da barra com pelo menos 44 px")
            movido = b.new_context(viewport={"width": 1280, "height": 800}, reduced_motion="reduce")
            pm = movido.new_page()
            abrir(pm, base)
            escrita_ligada(pm)
            pm.click("#ag-plus")
            confere(pm.evaluate("getComputedStyle(document.querySelector('.ag-dialogo')).animationName") == "none", "prefers-reduced-motion: sem animação ao abrir")
            movido.close()
            cel = b.new_context(viewport={"width": 390, "height": 800}, has_touch=True, is_mobile=True)
            pc = cel.new_page()
            abrir(pc, base)
            escrita_ligada(pc)
            largura = pc.evaluate("document.documentElement.scrollWidth")  # o menu do celular já estoura a largura hoje (peça 4)
            pc.evaluate("document.querySelector('#ag-plus').click()")
            pc.screenshot(path=f"{TELAS}/08-paleta-celular.png")
            confere(pc.evaluate("(() => { const r = document.querySelector('.ag-dialogo').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth; })()")
                    and pc.evaluate("document.documentElement.scrollWidth") == largura, "celular: a barra de comandos cabe na tela e não aumenta a rolagem horizontal")
            cel.close()
            b.close()
    finally:
        srv.terminate()
        shutil.rmtree(tmp, ignore_errors=True)
    fim()


main()
